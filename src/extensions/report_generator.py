"""
report_generator.py
-------------------
MAGI+ Extension 5: Clinical Report Generator

The original MAGI produces PsyCoT reasoning traces but no structured output
suitable for clinical use. Clinicians need a formatted document they can
attach to patient records or review quickly.

This module auto-generates a Clinical Assessment Report containing:
  - Session metadata
  - Disorder screening results with PsyCoT reasoning traces
  - Emotion arc timeline
  - Standardized severity scores (PHQ-9, GAD-7, C-SSRS)
  - Treatment recommendations
  - Longitudinal comparison (if returning participant)
  - AI disclaimer

Output formats: Markdown (primary), plain text (fallback)
"""

from __future__ import annotations
from datetime import datetime
from typing import Optional
from src.utils.data_models import (
    InterviewSession, DiagnosisResult, Disorder,
    RecommendationTier, SeverityLevel
)


# ─────────────────────────────────────────────
# CONSTANTS
# ─────────────────────────────────────────────

AI_DISCLAIMER = (
    "⚠️ **AI-ASSISTED ASSESSMENT DISCLAIMER**\n"
    "This report was generated by MAGI+, an AI-assisted psychiatric screening system. "
    "It is NOT a clinical diagnosis and does NOT replace evaluation by a licensed "
    "mental health professional. All findings must be reviewed and validated by a "
    "qualified clinician before any clinical decisions are made. "
    "If there is immediate risk to safety, call 988 or emergency services."
)

DISORDER_DISPLAY_NAMES = {
    "depression": "Major Depressive Episode",
    "generalized_anxiety": "Generalized Anxiety Disorder",
    "social_anxiety": "Social Anxiety Disorder",
    "suicide_risk": "Suicide Risk",
}

DSM5_CODES = {
    "depression": "F32.x",
    "generalized_anxiety": "F41.1",
    "social_anxiety": "F40.10",
    "suicide_risk": "Z91.5x",
}

RESULT_ICONS = {
    DiagnosisResult.YES: "✅ POSITIVE",
    DiagnosisResult.NO: "❌ NEGATIVE",
    DiagnosisResult.UNCERTAIN: "⚠️ UNCERTAIN",
}

SEVERITY_ICONS = {
    SeverityLevel.NONE: "○ None",
    SeverityLevel.MINIMAL: "● Minimal",
    SeverityLevel.MILD: "●● Mild",
    SeverityLevel.MODERATE: "●●● Moderate",
    SeverityLevel.MODERATELY_SEVERE: "●●●● Moderately Severe",
    SeverityLevel.SEVERE: "●●●●● Severe",
}

URGENCY_LABELS = {
    "routine": "📅 Routine",
    "soon": "🔔 Soon (within 1-2 weeks)",
    "urgent": "⚡ Urgent (within 24-48 hours)",
    "immediate": "🚨 IMMEDIATE ACTION REQUIRED",
}


# ─────────────────────────────────────────────
# REPORT GENERATOR
# ─────────────────────────────────────────────

class ReportGenerator:
    """
    Generates structured Clinical Assessment Reports from completed sessions.
    """

    def generate_markdown(
        self,
        session: InterviewSession,
        longitudinal_summary: Optional[str] = None,
    ) -> str:
        """
        Generate a full clinical report in Markdown format.

        Args:
            session: A completed InterviewSession
            longitudinal_summary: Optional text from LongitudinalMemory

        Returns:
            Full report as a Markdown string
        """
        sections = [
            self._header(session),
            self._disclaimer(),
            self._session_metadata(session),
            self._diagnostic_results(session),
            self._severity_scores(session),
            self._emotion_arc(session),
            self._longitudinal_section(longitudinal_summary),
            self._recommendations_section(session),
            self._psycot_traces(session),
            self._footer(session),
        ]

        return "\n\n---\n\n".join(s for s in sections if s.strip())

    def generate_plain_text(
        self,
        session: InterviewSession,
        longitudinal_summary: Optional[str] = None,
    ) -> str:
        """
        Generate a plain text version of the report (no Markdown formatting).
        Useful for systems that don't render Markdown.
        """
        md = self.generate_markdown(session, longitudinal_summary)
        # Strip Markdown formatting
        import re
        text = re.sub(r'\*\*(.*?)\*\*', r'\1', md)   # bold
        text = re.sub(r'#{1,6} ', '', text)            # headers
        text = re.sub(r'`(.*?)`', r'\1', text)         # inline code
        text = re.sub(r'---+', '-' * 60, text)         # horizontal rules
        return text

    def save_report(
        self,
        session: InterviewSession,
        output_dir: str,
        longitudinal_summary: Optional[str] = None,
        format: str = "markdown",
    ) -> str:
        """
        Save the report to a file.

        Args:
            session: Completed interview session
            output_dir: Directory to save the report
            longitudinal_summary: Optional longitudinal comparison text
            format: 'markdown' or 'text'

        Returns:
            Path to the saved file
        """
        import os
        os.makedirs(output_dir, exist_ok=True)

        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        ext = "md" if format == "markdown" else "txt"
        filename = f"report_{session.participant_id}_{session.session_number}_{timestamp}.{ext}"
        filepath = os.path.join(output_dir, filename)

        if format == "markdown":
            content = self.generate_markdown(session, longitudinal_summary)
        else:
            content = self.generate_plain_text(session, longitudinal_summary)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

        print(f"[Report] Saved to {filepath}")
        return filepath

    # ── REPORT SECTIONS ───────────────────────

    def _header(self, session: InterviewSession) -> str:
        return (
            f"# MAGI+ Clinical Assessment Report\n\n"
            f"**MAGI+: Multi-Agent Guided Interview — Extended System**  \n"
            f"*Based on MAGI (Bi et al., 2025) — arXiv:2504.18260*"
        )

    def _disclaimer(self) -> str:
        return AI_DISCLAIMER

    def _session_metadata(self, session: InterviewSession) -> str:
        date_str = session.created_at.strftime("%B %d, %Y at %H:%M UTC")
        duration = f"{session.duration_minutes:.0f} minutes" if session.duration_minutes else "N/A"
        completed = "✅ Complete" if session.completed_at else "⚠️ Incomplete"

        lines = [
            "## Session Information",
            "",
            f"| Field | Value |",
            f"|-------|-------|",
            f"| **Session ID** | `{session.session_id}` |",
            f"| **Participant ID** | `{session.participant_id}` |",
            f"| **Session Number** | {session.session_number} |",
            f"| **Date** | {date_str} |",
            f"| **Duration** | {duration} |",
            f"| **Status** | {completed} |",
            f"| **Total Turns** | {session.total_turns} |",
            f"| **Model Used** | {session.llm_model_used} |",
        ]
        return "\n".join(lines)

    def _diagnostic_results(self, session: InterviewSession) -> str:
        if not session.diagnoses:
            return "## Diagnostic Results\n\n*No diagnostic data available.*"

        lines = [
            "## Diagnostic Results",
            "",
            "| Disorder | DSM-5 Code | Result | Confidence |",
            "|----------|-----------|--------|------------|",
        ]

        for disorder_key, trace in session.diagnoses.items():
            name = DISORDER_DISPLAY_NAMES.get(disorder_key, disorder_key)
            code = DSM5_CODES.get(disorder_key, "—")
            result_icon = RESULT_ICONS.get(trace.result, trace.result.value)
            conf = f"{trace.confidence:.0%}"
            lines.append(f"| {name} | `{code}` | {result_icon} | {conf} |")

        # Add positive diagnoses summary
        positive = [
            DISORDER_DISPLAY_NAMES.get(k, k)
            for k, v in session.diagnoses.items()
            if v.result == DiagnosisResult.YES
        ]
        uncertain = [
            DISORDER_DISPLAY_NAMES.get(k, k)
            for k, v in session.diagnoses.items()
            if v.result == DiagnosisResult.UNCERTAIN
        ]

        lines.append("")
        if positive:
            lines.append(f"**Positive findings:** {', '.join(positive)}")
        else:
            lines.append("**Positive findings:** None — no disorders met diagnostic threshold.")

        if uncertain:
            lines.append(f"**Uncertain findings (require clinical review):** {', '.join(uncertain)}")

        return "\n".join(lines)

    def _severity_scores(self, session: InterviewSession) -> str:
        if not session.severity_report:
            return "## Severity Scores\n\n*Severity assessment not available.*"

        sr = session.severity_report
        lines = ["## Severity Scores", ""]

        if sr.phq9:
            sev = SEVERITY_ICONS.get(sr.phq9.severity, sr.phq9.severity.value)
            lines.append(f"### PHQ-9 (Depression Severity)")
            lines.append(f"**Score:** {sr.phq9.score} / 27 — {sev}")
            if sr.phq9.item_scores:
                lines.append("")
                lines.append("| Symptom | Score |")
                lines.append("|---------|-------|")
                for item, score in sr.phq9.item_scores.items():
                    lines.append(f"| {item.replace('_', ' ').title()} | {score}/3 |")
            lines.append("")

        if sr.gad7:
            sev = SEVERITY_ICONS.get(sr.gad7.severity, sr.gad7.severity.value)
            lines.append(f"### GAD-7 (Anxiety Severity)")
            lines.append(f"**Score:** {sr.gad7.score} / 21 — {sev}")
            lines.append("")

        if sr.cssrs:
            lines.append(f"### C-SSRS (Suicide Risk)")
            lines.append(f"**Ideation Level:** {sr.cssrs.ideation_level} / 5")
            lines.append(f"**Risk Category:** {sr.cssrs.risk_category.upper()}")
            lines.append(f"**Severity:** {SEVERITY_ICONS.get(sr.cssrs.severity, sr.cssrs.severity.value)}")
            lines.append(f"**Past Behavior Present:** {'Yes ⚠️' if sr.cssrs.behavior_present else 'No'}")
            lines.append("")

        sev_overall = SEVERITY_ICONS.get(sr.overall_severity, sr.overall_severity.value)
        lines.append(f"### Overall Severity")
        lines.append(f"**{sev_overall}**")

        return "\n".join(lines)

    def _emotion_arc(self, session: InterviewSession) -> str:
        if not session.emotion_arc:
            return "## Emotional Profile\n\n*Emotion tracking data not available.*"

        arc = session.emotion_arc
        lines = ["## Emotional Profile (EmotionArc)", ""]

        if arc.summary:
            lines.append(arc.summary)
            lines.append("")

        if arc.dominant_emotion:
            lines.append(f"**Dominant emotion:** {arc.dominant_emotion.value.title()}")

        if arc.peak_distress_turn is not None:
            lines.append(f"**Peak distress at turn:** {arc.peak_distress_turn}")

        escalation_status = "⚠️ YES — Clinician follow-up recommended" if arc.distress_escalation_detected else "No"
        lines.append(f"**Distress escalation detected:** {escalation_status}")

        # Emotion timeline (abbreviated)
        if arc.data_points:
            lines.append("")
            lines.append("**Emotion timeline (selected turns):**")
            lines.append("")
            lines.append("| Turn | Emotion | Intensity |")
            lines.append("|------|---------|-----------|")
            # Show every 3rd turn to keep report concise
            for point in arc.data_points[::3]:
                bar = "█" * int(point.intensity * 5)
                lines.append(
                    f"| {point.turn_id} | {point.emotion.value.title()} | {bar} {point.intensity:.2f} |"
                )

        return "\n".join(lines)

    def _longitudinal_section(self, longitudinal_summary: Optional[str]) -> str:
        if not longitudinal_summary:
            return ""

        return f"## Longitudinal Comparison\n\n{longitudinal_summary}"

    def _recommendations_section(self, session: InterviewSession) -> str:
        if not session.recommendations:
            return "## Recommendations\n\n*Recommendations not available.*"

        rec = session.recommendations
        lines = ["## Treatment Recommendations", ""]

        # Crisis alert
        if rec.crisis_flag:
            lines.append(f"### 🚨 CRISIS ALERT")
            lines.append(f"> {rec.crisis_message}")
            lines.append("")

        # Primary recommendation
        primary = rec.primary_recommendation
        urgency_label = URGENCY_LABELS.get(primary.urgency, primary.urgency)
        tier_label = primary.tier.value.replace("_", " ").title()

        lines.append(f"### Primary Recommendation — {tier_label}")
        lines.append(f"**{primary.title}**")
        lines.append("")
        lines.append(primary.description)
        lines.append(f"**Urgency:** {urgency_label}")

        if primary.resources:
            lines.append("")
            lines.append("**Recommended resources:**")
            for resource in primary.resources:
                lines.append(f"  - {resource}")

        # Additional recommendations
        if rec.additional_recommendations:
            lines.append("")
            lines.append("### Additional Recommendations")
            for i, add_rec in enumerate(rec.additional_recommendations, 1):
                tier_name = add_rec.tier.value.replace("_", " ").title()
                lines.append(f"**{i}. {add_rec.title}** *({tier_name})*")
                lines.append(add_rec.description)
                if add_rec.resources:
                    for r in add_rec.resources[:3]:  # Max 3 for brevity
                        lines.append(f"  - {r}")
                lines.append("")

        # Disclaimer
        lines.append("")
        lines.append(f"*{rec.disclaimer}*")

        return "\n".join(lines)

    def _psycot_traces(self, session: InterviewSession) -> str:
        if not session.diagnoses:
            return ""

        lines = ["## PsyCoT Reasoning Traces", "",
                 "*Detailed clinical reasoning for each disorder assessment:*", ""]

        for disorder_key, trace in session.diagnoses.items():
            name = DISORDER_DISPLAY_NAMES.get(disorder_key, disorder_key)
            result_icon = RESULT_ICONS.get(trace.result, trace.result.value)

            lines.append(f"### {name} — {result_icon}")
            lines.append("")

            # Phase 1
            lines.append("**Phase 1 — Symptom Anchoring:**")
            if trace.symptoms_confirmed:
                lines.append(f"  - Confirmed: {', '.join(trace.symptoms_confirmed)}")
            if trace.symptoms_denied:
                lines.append(f"  - Denied: {', '.join(trace.symptoms_denied)}")
            if trace.temporal_verification:
                lines.append(f"  - Duration: {trace.temporal_verification}")
            if trace.exclusion_checks:
                lines.append(f"  - Exclusions: {trace.exclusion_checks}")

            # Phase 2
            lines.append("")
            lines.append("**Phase 2 — Diagnostic Synthesis:**")
            lines.append(
                f"  - Symptoms confirmed: {trace.criteria_met_count} / {trace.criteria_required} required"
            )
            threshold_icon = "✅" if trace.threshold_passed else "❌"
            lines.append(f"  - Threshold passed: {threshold_icon}")

            # Phase 3
            if trace.key_evidence:
                lines.append("")
                lines.append("**Phase 3 — Key Evidence:**")
                for evidence in trace.key_evidence[:3]:  # Max 3 quotes
                    lines.append(f'  > *"{evidence}"*')

            if trace.reasoning_summary:
                lines.append("")
                lines.append(f"**Clinical reasoning:** {trace.reasoning_summary}")

            lines.append("")

        return "\n".join(lines)

    def _footer(self, session: InterviewSession) -> str:
        generated_at = datetime.utcnow().strftime("%B %d, %Y at %H:%M UTC")
        return (
            f"---\n\n"
            f"*Report generated by MAGI+ v1.0 on {generated_at}*  \n"
            f"*Original MAGI framework: Bi, Chen et al. (2025), arXiv:2504.18260*  \n"
            f"*Extended by MAGI+ Research Team*  \n"
            f"*This document is confidential and intended for clinical review only.*"
        )
